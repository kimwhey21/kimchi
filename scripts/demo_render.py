def _attach_placeholder_images(generated: dict) -> dict:
    """데모용: Unsplash 대신 Picsum 플레이스홀더 이미지를 소재별로 붙여줍니다.
    실제 파이프라인(main.py)에서는 이 자리에 fetch_images.attach_images()가 대신 들어갑니다."""
    stories = generated.get("insight_section", {}).get("stories", [])
    for story in stories:
        seed = next(
            (v for k, v in PLACEHOLDER_IMAGE_SEEDS.items() if k in story["heading"]),
            "finance",
        )
        story["image"] = {
            "url": f"https://picsum.photos/seed/{seed}/800/450",
            "alt": story["heading"],
            "photographer": "Picsum (데모용 예시 이미지)",
            "photographer_url": "https://picsum.photos",
        }
    return generated


